#Arithmetic and math


friends = 5

# Addition:  friends = friends + 1
friends += 1
print(friends)


# Subtraction: friends = friends - 1
friends -=1
print(friends)

# Multiplication: friends = friends * 3
friends *=3
print(friends)

# Division: friends = friends / 2
friends /=2
print(friends)

# Power: friends = friends ** 2
friends **=2
print(friends)

#Remainder (modulus): friends = friends % 3
friends %=3
print(friends)

